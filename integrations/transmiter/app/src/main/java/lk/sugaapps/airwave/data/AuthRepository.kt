package lk.sugaapps.airwave.data

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider

/**
 * Firebase Authentication wrapper (competition/Google code — public).
 * Supports email/password and Google Sign-In (via Credential Manager).
 */
object AuthRepository {

    private val auth: FirebaseAuth get() = FirebaseAuth.getInstance()

    val currentUser: FirebaseUser? get() = auth.currentUser

    fun addAuthStateListener(listener: (FirebaseUser?) -> Unit): FirebaseAuth.AuthStateListener {
        val l = FirebaseAuth.AuthStateListener { listener(it.currentUser) }
        auth.addAuthStateListener(l)
        return l
    }

    fun removeAuthStateListener(listener: FirebaseAuth.AuthStateListener) {
        auth.removeAuthStateListener(listener)
    }

    suspend fun signUpEmail(email: String, password: String): FirebaseUser {
        val result = auth.createUserWithEmailAndPassword(email.trim(), password).await()
        return result.user ?: error("No user after sign-up")
    }

    suspend fun loginEmail(email: String, password: String): FirebaseUser {
        val result = auth.signInWithEmailAndPassword(email.trim(), password).await()
        return result.user ?: error("No user after login")
    }

    /**
     * Google Sign-In. Resolves the web client id generated by the google-services
     * plugin at runtime, so the project still compiles before Google is enabled in
     * the Firebase console. Throws [GoogleNotConfigured] if it isn't set up yet.
     */
    suspend fun signInWithGoogle(context: Context): FirebaseUser {
        val resId = context.resources.getIdentifier(
            "default_web_client_id", "string", context.packageName
        )
        if (resId == 0) throw GoogleNotConfigured()
        val webClientId = context.getString(resId)

        val googleOption = GetGoogleIdOption.Builder()
            .setServerClientId(webClientId)
            .setFilterByAuthorizedAccounts(false)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleOption)
            .build()

        val response = CredentialManager.create(context).getCredential(context, request)
        val googleCred = GoogleIdTokenCredential.createFrom(response.credential.data)
        val firebaseCred = GoogleAuthProvider.getCredential(googleCred.idToken, null)
        val result = auth.signInWithCredential(firebaseCred).await()
        return result.user ?: error("No user after Google sign-in")
    }

    fun signOut() = auth.signOut()

    class GoogleNotConfigured :
        Exception("Google sign-in isn't configured yet. Enable Google in Firebase Auth, add the SHA-1, and re-download google-services.json.")
}
